export function useReviewWords() {
  const { locale } = useT();
  return { w: locale === "fa" ? fa : en, locale };
}
export function valueLabel(value: string | null, w: Words) {
  if (!value) return "—";
  if (/^gt-(foundation|intermediate|advanced)$/.test(value))
    value = value.slice(3);
  if (value === "listening") return w.listeningLabel;
  if (value === "speaking") return w.speakingLabel;
  return value in w ? w[value as keyof Words] : value.replaceAll("_", " ");
}
